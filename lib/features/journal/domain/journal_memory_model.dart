import 'package:flutter/foundation.dart';

/// Categories of compressed journal memory in Mind Forensics.
enum JournalMemoryCategory {
  /// Information explicitly shared by the user (preferences, personal context, goals).
  userStatedContext,

  /// Topics or themes that appear repeatedly across multiple journal entries.
  recurringTheme,

  /// Repeated self-reported affective or bodily emotional experiences.
  emotionalContext,

  /// Strategies or actions the user identified as helpful or unhelpful.
  copingExperience,

  /// Unresolved concerns, open inquiries, or questions to revisit.
  openQuestion,

  /// Potential non-causal patterns observed across entries, explicitly framed as hypotheses.
  tentativeObservation;

  String get displayName {
    switch (this) {
      case JournalMemoryCategory.userStatedContext:
        return 'User-Stated Context';
      case JournalMemoryCategory.recurringTheme:
        return 'Recurring Theme';
      case JournalMemoryCategory.emotionalContext:
        return 'Emotional Context';
      case JournalMemoryCategory.copingExperience:
        return 'Coping Strategy';
      case JournalMemoryCategory.openQuestion:
        return 'Open Question';
      case JournalMemoryCategory.tentativeObservation:
        return 'Tentative Observation';
    }
  }
}

/// Evidentiary classification of a compressed memory item.
enum MemoryEvidenceStatus {
  /// Explicitly stated by the user in their own words.
  userExplicit,

  /// Repeatedly reported across multiple distinct entries.
  recurringReported,

  /// Tentative hypothesis or observed correlation (never a proven cause or diagnosis).
  tentativeHypothesis;

  String get displayName {
    switch (this) {
      case MemoryEvidenceStatus.userExplicit:
        return 'User-Stated';
      case MemoryEvidenceStatus.recurringReported:
        return 'Recurring Report';
      case MemoryEvidenceStatus.tentativeHypothesis:
        return 'Tentative Hypothesis';
    }
  }
}

/// User review status for transparent memory control.
enum MemoryConfirmationStatus {
  /// Generated by local compression, awaiting user review.
  unreviewed,

  /// Affirmed by the user as accurate.
  confirmed,

  /// Dismissed or rejected by the user. Strictly omitted from AI context.
  rejected;

  String get displayName {
    switch (this) {
      case MemoryConfirmationStatus.unreviewed:
        return 'Unreviewed';
      case MemoryConfirmationStatus.confirmed:
        return 'Confirmed';
      case MemoryConfirmationStatus.rejected:
        return 'Rejected';
    }
  }
}

/// Represents a structured, compact unit of journal-derived memory.
///
/// Section 3 & Step 3.2:
/// - Never replaces raw entries; provides compact synthesized context for AI.
/// - Retains full source traceability back to original entries.
/// - Strictly avoids clinical labels, diagnosis, or permanence claims.
@immutable
class JournalMemoryModel {
  const JournalMemoryModel({
    required this.id,
    this.userId = 'local_user',
    required this.category,
    required this.summary,
    required this.sourceEntryIds,
    this.observationCount = 1,
    this.evidenceStatus = MemoryEvidenceStatus.userExplicit,
    this.confirmationStatus = MemoryConfirmationStatus.unreviewed,
    required this.firstObservedDate,
    required this.lastObservedDate,
    this.isArchived = false,
    required this.createdAt,
    required this.updatedAt,
  });

  /// Unique identifier (UUID).
  final String id;

  /// User identifier for multi-user sovereign isolation.
  final String userId;

  /// Semantic memory category.
  final JournalMemoryCategory category;

  /// Concise, truthful summary of the observation without clinical jargon.
  final String summary;

  /// IDs of the source MindTraceModel or CaseModel entries this was extracted from.
  final List<String> sourceEntryIds;

  /// Total number of distinct observations supporting this memory.
  final int observationCount;

  /// Epistemic evidence status.
  final MemoryEvidenceStatus evidenceStatus;

  /// User control and confirmation status.
  final MemoryConfirmationStatus confirmationStatus;

  /// Date when this memory theme was first logged.
  final DateTime firstObservedDate;

  /// Date when this memory theme was most recently logged.
  final DateTime lastObservedDate;

  /// Whether this memory has been retired or archived.
  final bool isArchived;

  final DateTime createdAt;
  final DateTime updatedAt;

  bool get isConfirmed => confirmationStatus == MemoryConfirmationStatus.confirmed;
  bool get isRejected => confirmationStatus == MemoryConfirmationStatus.rejected;
  bool get isTentative => evidenceStatus == MemoryEvidenceStatus.tentativeHypothesis;
  bool get isRecurring => observationCount >= 2;

  JournalMemoryModel copyWith({
    String? id,
    String? userId,
    JournalMemoryCategory? category,
    String? summary,
    List<String>? sourceEntryIds,
    int? observationCount,
    MemoryEvidenceStatus? evidenceStatus,
    MemoryConfirmationStatus? confirmationStatus,
    DateTime? firstObservedDate,
    DateTime? lastObservedDate,
    bool? isArchived,
    DateTime? createdAt,
    DateTime? updatedAt,
  }) {
    return JournalMemoryModel(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      category: category ?? this.category,
      summary: summary ?? this.summary,
      sourceEntryIds: sourceEntryIds ?? this.sourceEntryIds,
      observationCount: observationCount ?? this.observationCount,
      evidenceStatus: evidenceStatus ?? this.evidenceStatus,
      confirmationStatus: confirmationStatus ?? this.confirmationStatus,
      firstObservedDate: firstObservedDate ?? this.firstObservedDate,
      lastObservedDate: lastObservedDate ?? this.lastObservedDate,
      isArchived: isArchived ?? this.isArchived,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'userId': userId,
      'category': category.name,
      'summary': summary,
      'sourceEntryIds': sourceEntryIds,
      'observationCount': observationCount,
      'evidenceStatus': evidenceStatus.name,
      'confirmationStatus': confirmationStatus.name,
      'firstObservedDate': firstObservedDate.toIso8601String(),
      'lastObservedDate': lastObservedDate.toIso8601String(),
      'isArchived': isArchived,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt.toIso8601String(),
    };
  }

  factory JournalMemoryModel.fromJson(Map<String, dynamic> json) {
    return JournalMemoryModel(
      id: json['id'] as String,
      userId: (json['userId'] as String?) ?? 'local_user',
      category: JournalMemoryCategory.values.firstWhere(
        (c) => c.name == json['category'],
        orElse: () => JournalMemoryCategory.userStatedContext,
      ),
      summary: json['summary'] as String,
      sourceEntryIds: (json['sourceEntryIds'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      observationCount: (json['observationCount'] as int?) ?? 1,
      evidenceStatus: MemoryEvidenceStatus.values.firstWhere(
        (e) => e.name == json['evidenceStatus'],
        orElse: () => MemoryEvidenceStatus.userExplicit,
      ),
      confirmationStatus: MemoryConfirmationStatus.values.firstWhere(
        (s) => s.name == json['confirmationStatus'],
        orElse: () => MemoryConfirmationStatus.unreviewed,
      ),
      firstObservedDate: DateTime.parse(json['firstObservedDate'] as String),
      lastObservedDate: DateTime.parse(json['lastObservedDate'] as String),
      isArchived: (json['isArchived'] as bool?) ?? false,
      createdAt: DateTime.parse(json['createdAt'] as String),
      updatedAt: DateTime.parse(json['updatedAt'] as String),
    );
  }
}
